/**
 * Demo "Job posting" output: a job post PDF in a social-job-board style layout.
 * Deliberately no LinkedIn logo, name or brand colours (context §4 Flow 1 step 8).
 * In the real build this file is produced by an Opus Code step and returned as a file result.
 */
import "server-only";
import { PDFDocument, PDFFont, PDFPage, StandardFonts, rgb } from "pdf-lib";
import type { Requisition } from "@/domain/types";
import { formatMyt, range } from "@/lib/format";

const INK = rgb(0.114, 0.114, 0.114);
const MUTED = rgb(0.36, 0.36, 0.36);
const CHIP = rgb(0.933, 0.953, 0.973);
const ACCENT = rgb(0.043, 0.341, 0.816); // #0b57d0
const LOGO = rgb(0.149, 0.196, 0.22); // #263238
const RULE = rgb(0.878, 0.878, 0.878);

function safe(font: PDFFont, text: string): string {
  let out = "";
  for (const ch of text) {
    try {
      font.encodeText(ch);
      out += ch;
    } catch {
      out += ch === "–" || ch === "—" ? "-" : "?";
    }
  }
  return out;
}

function wrap(font: PDFFont, text: string, size: number, width: number): string[] {
  const words = safe(font, text).split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    const next = line ? `${line} ${w}` : w;
    if (font.widthOfTextAtSize(next, size) > width && line) {
      lines.push(line);
      line = w;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}

function pill(page: PDFPage, x: number, yTop: number, w: number, h: number, color: ReturnType<typeof rgb>) {
  const r = h / 2;
  const path = `M ${r} 0 L ${w - r} 0 A ${r} ${r} 0 0 1 ${w - r} ${h} L ${r} ${h} A ${r} ${r} 0 0 1 ${r} 0 Z`;
  page.drawSvgPath(path, { x, y: yTop, color });
}

function fakeQr(page: PDFPage, x: number, yTop: number, size: number, seedText: string) {
  const n = 21;
  const cell = size / n;
  let seed = 7;
  for (const ch of seedText) seed = (seed * 31 + ch.charCodeAt(0)) >>> 0;
  const rnd = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 4294967296);
  const finder = (cx: number, cy: number, i: number, j: number) => {
    const di = i - cx, dj = j - cy;
    if (di < 0 || dj < 0 || di > 6 || dj > 6) return null;
    const ring = Math.max(Math.abs(di - 3), Math.abs(dj - 3));
    return ring === 3 || ring <= 1;
  };
  page.drawRectangle({ x: x - 4, y: yTop - size - 4, width: size + 8, height: size + 8, color: rgb(1, 1, 1), borderColor: RULE, borderWidth: 1 });
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < n; j++) {
      const f = finder(0, 0, i, j) ?? finder(n - 7, 0, i, j) ?? finder(0, n - 7, i, j);
      const on = f ?? rnd() > 0.5;
      if (on) page.drawRectangle({ x: x + i * cell, y: yTop - (j + 1) * cell, width: cell, height: cell, color: INK });
    }
  }
}

export async function buildJobPostPdf(r: Requisition): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`${r.role} · ${r.store} · ${r.id}`);
  doc.setAuthor("Valiram Hiring (demo)");
  doc.setSubject("Job post generated by the Opus Job posting step (demo)");
  doc.setCreator("Valiram Hiring demo · pdf-lib");
  const regular = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);

  let page = doc.addPage([595.28, 841.89]);
  const M = 48;
  const W = page.getWidth() - M * 2;
  let y = page.getHeight() - M;

  const text = (t: string, opts: { size?: number; font?: PDFFont; color?: ReturnType<typeof rgb>; x?: number }) => {
    const size = opts.size ?? 11;
    const font = opts.font ?? regular;
    page.drawText(safe(font, t), { x: opts.x ?? M, y: y - size, size, font, color: opts.color ?? INK });
  };

  const ensure = (h: number) => {
    if (y - h < M + 30) {
      page = doc.addPage([595.28, 841.89]);
      y = page.getHeight() - M;
    }
  };

  // Header: company mark + title
  page.drawRectangle({ x: M, y: y - 56, width: 56, height: 56, color: LOGO });
  page.drawText("V", { x: M + 19, y: y - 38, size: 24, font: bold, color: rgb(1, 1, 1) });
  const hx = M + 72;
  text(r.role, { size: 20, font: bold, x: hx });
  y -= 26;
  text(`Valiram · ${r.store}, ${r.region === "Pahang" ? "Pahang" : "Kuala Lumpur area"} (On-site)`, { size: 11.5, color: MUTED, x: hx });
  y -= 16;
  text(`Posted ${formatMyt(r.posting?.generated_at ?? new Date().toISOString(), "date")} · ${r.department}`, { size: 10.5, color: MUTED, x: hx });
  y -= 30;

  // Chips
  let cx = M;
  for (const c of [r.employment_type, `${range(r.base_min, r.base_max)} / month + commission`, `${r.openings} opening${r.openings > 1 ? "s" : ""}`]) {
    const w = regular.widthOfTextAtSize(safe(regular, c), 10.5) + 20;
    pill(page, cx, y, w, 20, CHIP);
    page.drawText(safe(regular, c), { x: cx + 10, y: y - 14, size: 10.5, font: regular, color: INK });
    cx += w + 8;
  }
  y -= 36;

  // Apply button + QR
  const apply = "Apply · video interview";
  const bw = bold.widthOfTextAtSize(safe(bold, apply), 12) + 40;
  pill(page, M, y, bw, 30, ACCENT);
  page.drawText(safe(bold, apply), { x: M + 20, y: y - 20, size: 12, font: bold, color: rgb(1, 1, 1) });
  page.drawText(safe(regular, `kitahq.example/apply/${r.id} · no CV needed`), { x: M + bw + 12, y: y - 19, size: 9.5, font: regular, color: MUTED });
  fakeQr(page, M + W - 78, y + 4, 78, r.id);
  page.drawText("Scan to apply (demo QR)", { x: M + W - 92, y: y - 90, size: 8, font: regular, color: MUTED });
  y -= 104;

  page.drawLine({ start: { x: M, y }, end: { x: M + W, y }, thickness: 1, color: RULE });
  y -= 14;

  const jd = r.jd_sections;
  const sections: [string, string[] | string][] = [
    ["About the job", jd.about],
    ["What you will do", jd.duties],
    ["What we look for", jd.requirements],
    ["Benefits", jd.benefits],
    ...(jd.shift_pattern?.trim() ? ([["Shift pattern", jd.shift_pattern]] as [string, string][]) : []),
    ["How to apply", jd.how_to_apply],
  ];
  for (const [title, body] of sections) {
    ensure(40);
    text(title, { size: 12.5, font: bold });
    y -= 20;
    const items = Array.isArray(body) ? body : [body];
    for (const item of items) {
      const prefix = Array.isArray(body) ? "•  " : "";
      const lines = wrap(regular, item, 11, W - (prefix ? 14 : 0));
      lines.forEach((ln, i) => {
        ensure(16);
        if (prefix && i === 0) page.drawText("•", { x: M, y: y - 11, size: 11, font: regular, color: INK });
        page.drawText(ln, { x: M + (prefix ? 14 : 0), y: y - 11, size: 11, font: regular, color: INK });
        y -= 16;
      });
    }
    y -= 10;
  }

  for (const p of doc.getPages()) {
    p.drawText(safe(regular, `${r.id} · Demo job post generated by the Opus "Job posting" step · ${formatMyt(r.posting?.generated_at, "full")}`), {
      x: M,
      y: 28,
      size: 8,
      font: regular,
      color: MUTED,
    });
  }
  return doc.save();
}
